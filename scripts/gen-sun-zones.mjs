// Regenerates src/sun-zones.ts from the IANA tz database (LOOK-SCHEDULE.md §3).
// Run when the tz database adds or renames a zone:  node scripts/gen-sun-zones.mjs
import fs from "fs";

const BASE = "https://raw.githubusercontent.com/eggert/tz/main/";
const [zoneTab, backward] = await Promise.all(
  ["zone.tab", "backward"].map((f) => fetch(BASE + f).then((r) => (r.ok ? r.text() : Promise.reject(new Error(`${f}: ${r.status}`))))),
);

// ±DDMM[SS] / ±DDDMM[SS] → degrees.
const deg = (s, w) => {
  const sign = s[0] === "-" ? -1 : 1;
  return sign * (+s.slice(1, 1 + w) + +s.slice(1 + w, 3 + w) / 60 + +(s.slice(3 + w) || 0) / 3600);
};
const round = (x) => Math.round(x * 10) / 10;

const zones = {};
for (const line of zoneTab.split("\n")) {
  if (!line || line[0] === "#") continue;
  const [, coords, name] = line.split("\t");
  const m = /^([+-]\d{4,6})([+-]\d{5,7})$/.exec(coords);
  zones[name] = [round(deg(m[1], 2)), round(deg(m[2], 3))];
}
const aliases = {};
for (const line of backward.split("\n")) {
  const p = line.split(/\t+/);
  if (p[0] !== "Link") continue;
  let target = p[1];
  while (!zones[target] && aliases[target]) target = aliases[target];
  if (zones[target]) aliases[p[2]] = target;
}

const z = Object.entries(zones).map(([k, v]) => `"${k}":[${v}]`).join(",");
const a = Object.entries(aliases).map(([k, v]) => `"${k}":"${v}"`).join(",");
fs.writeFileSync(
  new URL("../src/sun-zones.ts", import.meta.url),
  `// GENERATED by scripts/gen-sun-zones.mjs from the IANA tz database (zone.tab + backward),
// ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Each zone's main city: [latitude, longitude] in degrees, north and east positive.
// look-schedule.ts reads it to place the sun without the user's location.
export const ZONES: Record<string, [number, number]> = {${z}};
/** Old or other names (WebView2 can report "Asia/Calcutta") → the zone above. */
export const ALIASES: Record<string, string> = {${a}};
`,
);
console.log(`${Object.keys(zones).length} zones, ${Object.keys(aliases).length} aliases`);
