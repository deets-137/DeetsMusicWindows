// `npm run usage:keys`: copy the usage report's allow-list (src/usage-keys.ts) into the
// DeetsSupport worker (../DeetsSupport/src/usage-keys.js), whose /usage/settings route drops any
// key not on it (USAGE-COUNTS.md §4, §5). Run it after any change to the list; a worker deploy
// (the owner's call) then takes the new keys. Until that deploy, a new key is dropped, never
// stored. `--check` prints the difference and exits 1 instead of writing.
//
// Runs under tests/setup.mjs (package.json), which lets Node load the .ts list.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { REPORTED } from "../src/usage-keys.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "DeetsSupport", "src", "usage-keys.js");

export function workerFile(keys) {
  const lines = [...keys].sort().map((k) => `  ${JSON.stringify(k)},`);
  return [
    "/* GENERATED by DeetsMusic `npm run usage:keys` from its src/usage-keys.ts. Do not edit.",
    "   The settings a usage report may carry (DeetsMusic USAGE-COUNTS.md §4): /usage/settings",
    "   drops any other key. */",
    "export const SETTING_KEYS = new Set([",
    ...lines,
    "]);",
    "",
  ].join("\n");
}

const want = workerFile(REPORTED);
if (process.argv.includes("--check")) {
  const have = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (have !== want) {
    console.error(`[usage:keys] ${out} is out of date: run npm run usage:keys`);
    process.exit(1);
  }
  console.log("[usage:keys] the worker's list matches");
} else if (!existsSync(dirname(out))) {
  console.error(`[usage:keys] no DeetsSupport checkout at ${dirname(out)}`);
  process.exit(1);
} else {
  writeFileSync(out, want);
  console.log(`[usage:keys] wrote ${REPORTED.length} keys to ${out}`);
}
